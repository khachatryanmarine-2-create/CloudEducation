function renderGuide(id){
const info=document.getElementById("inf");
info.innerHTML="";
const data=guidesData[id];
if(!data)return;

const title=document.createElement("h1");
title.textContent=data.title;
info.append(title);

data.content.forEach(item=>{
let el;

if(item.type==="h2"){
el=document.createElement("h2");
el.textContent=item.text;
}
else if(item.type==="p"){
el=document.createElement("p");
el.innerHTML=item.text;
}
else if(item.type==="ul"){
el=document.createElement("ul");
item.items.forEach(text=>{
const li=document.createElement("li");
li.innerHTML=text;
el.append(li);
});
}
else if(item.type==="table"){
el=document.createElement("table");
const thead=el.createTHead();
const row=thead.insertRow();
item.headers.forEach(h=>{
const th=document.createElement("th");
th.textContent=h;
row.append(th);
});
const tbody=el.createTBody();
item.rows.forEach(r=>{
const tr=tbody.insertRow();
r.forEach(cell=>{
const td=tr.insertCell();
td.textContent=cell;
});
});
}
else if(item.type==="link"){
el=document.createElement("a");
el.href=item.url;
el.target="_blank";
el.className="support-link";
el.textContent=item.label;
}
else if (item.type === "video") {
    el = document.createElement("video");
    el.src = item.url;           // Տեսանյութի ֆայլի հղումը (օրինակ՝ video.mp4)
    el.controls = true;          // Ավելացնում է նվագարկման կոճակները (Play, Pause, Volume)
    el.style.width = "100%";     // Որպեսզի հարմարվի պատուհանի լայնությանը
    el.style.marginTop = "20px";
    el.style.borderRadius = "10px";
}

if(el)info.append(el);
});
}


document.querySelectorAll(".popup").forEach(btn=>{
btn.addEventListener("click",()=>{
document.getElementById("fon").style.transform="scale(1)";
renderGuide(btn.id);
});
});

document.getElementById("x").addEventListener("click",()=>{
document.getElementById("fon").style.transform="scale(0)";
});
